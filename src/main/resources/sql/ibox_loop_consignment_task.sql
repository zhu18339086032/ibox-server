CREATE TABLE `ibox_loop_consignment_task`
(
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `task_name` VARCHAR(100) NOT NULL COMMENT '任务名称',
    `account_id` BIGINT NOT NULL COMMENT '账号ID',
    `digital_collection_group_id` BIGINT NOT NULL COMMENT '商品组ID',
    `collection_name` VARCHAR(100) NOT NULL COMMENT '商品名称',
    `consign_price` DECIMAL(10, 2) NOT NULL COMMENT '上架价格',
    `list_item_interval_millis` BIGINT NOT NULL DEFAULT 3000 COMMENT '上架间隔(毫秒)',
    `after_list_to_delist_interval_millis` BIGINT NOT NULL DEFAULT 240000 COMMENT '全部上架后执行下架间隔(毫秒)',
    `delist_item_interval_millis` BIGINT NOT NULL DEFAULT 2000 COMMENT '下架间隔(毫秒)',
    `after_delist_to_list_interval_millis` BIGINT NOT NULL DEFAULT 240000 COMMENT '全部下架后执行上架间隔(毫秒)',
    `current_stage` VARCHAR(30) NOT NULL DEFAULT 'LISTING' COMMENT '当前阶段',
    `next_execute_time` DATETIME DEFAULT NULL COMMENT '下一次执行时间',
    `executed_round_count` INT NOT NULL DEFAULT 0 COMMENT '已执行轮次',
    `executed_count` INT NOT NULL DEFAULT 0 COMMENT '已处理总次数',
    `success_count` INT NOT NULL DEFAULT 0 COMMENT '成功次数',
    `fail_count` INT NOT NULL DEFAULT 0 COMMENT '失败次数',
    `status` TINYINT NOT NULL DEFAULT 1 COMMENT '任务状态，0-禁用，1-启用',
    `running` TINYINT NOT NULL DEFAULT 0 COMMENT '是否运行中，0-否，1-是',
    `last_message` VARCHAR(500) DEFAULT NULL COMMENT '最近结果',
    `remark` VARCHAR(500) DEFAULT NULL COMMENT '备注',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除标记，0-未删除，1-已删除',
    PRIMARY KEY (`id`),
    KEY `idx_account_id` (`account_id`),
    KEY `idx_group_id` (`digital_collection_group_id`),
    KEY `idx_status_running` (`status`, `running`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='循环上下架任务表';
